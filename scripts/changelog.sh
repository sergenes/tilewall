#!/bin/zsh
# Writes CHANGELOG.md from the release notes in docs/releases, newest first.
# Each notes file is named <version>.md and starts with a line "date: YYYY-MM-DD".
# With --check it only reports whether CHANGELOG.md is up to date.
set -euo pipefail
cd "$(dirname "$0")/.."

generate() {
    echo "<!-- Generated by scripts/changelog.sh from docs/releases. Do not edit: change the notes and run the script. -->"
    echo "# Changelog"
    for file in $(ls docs/releases/*.md | sort -t/ -k3 -V -r); do
        version="${file:t:r}"
        date="$(sed -n '1s/^date: *//p' "$file")"
        [[ -n "$date" ]] || { echo "$file does not start with a date line" >&2; exit 1; }
        echo
        echo "## [$version](https://github.com/sergenes/tilewall/releases/tag/v$version) - $date"
        tail -n +2 "$file"
    done
}

if [[ "${1:-}" == "--check" ]]; then
    generate | diff -q - CHANGELOG.md >/dev/null || { echo "CHANGELOG.md is out of date, run scripts/changelog.sh"; exit 1; }
else
    generate > CHANGELOG.md
    echo "wrote CHANGELOG.md"
fi
